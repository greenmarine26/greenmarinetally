export function hasHatchCovers(code) {
  const c = String(code || '').toUpperCase();
  return !!(HATCH_COVERS_BY_HATCH[c] || HATCH_COVERS_BY_BAY[c]);
}

// 해치번호·소속 베이들로 커버 장수를 찾는다. 모르면 null → 매트릭스에서 직접 입력.
export function lookupHatchCovers(code, hatchNo, bays) {
  const c = String(code || '').toUpperCase();
  const h = HATCH_COVERS_BY_HATCH[c];
  if (h && h[hatchNo] != null) return h[hatchNo];
  const b = HATCH_COVERS_BY_BAY[c];
  if (b) for (const v of (bays || [])) { const k = String(v).padStart(2, '0'); if (b[k] != null) return b[k]; }
  return null;
}
