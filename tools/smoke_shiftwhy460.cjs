// 4.60 연막검사 — 터미널 배정 이적은 있으나 앱이 컨을 못 찾는 배(작업 전)는 «시프팅 예상 N대 + 아직 알 수 없는 이유» 한 줄을 말하고, 자료가 와 확정되면 저절로 사라진다(실소스 번들).
const path = require('path'); const fs = require('fs'); const esbuild = require('esbuild');
let fail = 0; const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ ') + m); if (!c) fail++; };
(async () => {
  const out = path.join(require('os').tmpdir(), '_smoke_shiftwhy460_' + process.pid + '.cjs');
  await esbuild.build({ entryPoints: [path.join(__dirname, '..', 'src', 'utils.js')], bundle: true, platform: 'node', format: 'cjs', outfile: out, logLevel: 'silent' });
  global.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
  global.window = global.window || { addEventListener() {}, removeEventListener() {}, dispatchEvent() {} };
  global.document = global.document || { createElement: () => ({}), addEventListener() {} };
  const M = require(out); fs.unlinkSync(out);
  const core = M.shiftEvidenceCore;
  console.log('시프팅 설명 한 줄(4.60) — XTPG 546E 모양: 배정표 이적 16모브 · 작업 전 · 컨 0대');
  let r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: 'planned' });
  ok(r.line.includes('시프팅 예상 8대(터미널 배정 16모브)'), '① 예상 8대 · 터미널 배정 16모브를 적는다');
  ok(r.line.includes('앞 기항지 작업이 끝나기 전') && r.line.includes('어느 베이'), '② 아직 알 수 없는 이유를 적는다');
  ok(r.line.includes('사라집니다'), '③ 최종 자료가 오면 설명이 사라진다고 적는다');
  r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: 'working' });
  ok(!r.line.includes('앞 기항지'), '④ 터미널이 작업을 시작해 확정되면 설명이 없다');
  const m8 = {}; for (let i = 0; i < 8; i++) m8['ABCU000000' + i] = { from: '010202', to: '010402' };
  r = core({ shiftingMap: m8, berthShift: 16, terminalStatus: 'planned' });
  ok(!r.line.includes('앞 기항지'), '⑤ 컨 8대가 잡히면(자료가 오면) 설명이 없다');
  const dir = {}; Object.defineProperty(dir, '_meta', { value: { rot: 'direct' } });
  r = core({ shiftingMap: dir, berthShift: 16, terminalStatus: 'planned' });
  ok(!r.line.includes('앞 기항지'), '⑥ 직항(앞 기항지 없음)이면 설명이 없다');
  r = core({ shiftingMap: {}, berthShift: 0, terminalStatus: 'planned' });
  ok(!r.line.includes('앞 기항지') && !r.line.includes('시프팅 예상'), '⑦ 이적 0이면 아무 말도 하지 않는다');
  r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: 'planned', prevPort: '인천' });
  ok(r.line.includes('앞 기항지(인천) 작업이 끝나기 전'), '⑨ 항로 사전으로 앞 기항지를 알면 이름을 넣는다');
  M.setLaneRoutes({ TIS2: { rotation: ['KRINC', 'KRPTK', 'CNNTG', 'CNTAG'] }, ZZ9: { rotation: ['KRPTK', 'CNTAO'] } });
  ok(M.prevPortOfLane('TIS2') === '인천' && M.prevPortOfLane('ZZ9') === 'CNTAO' && M.prevPortOfLane('없음') === '', '⑩ 항로 사전에서 평택 바로 앞 기항지를 읽는다(인천은 한글, 그 밖은 코드, 모르면 빈 칸)');
  r = core({ shiftingMap: {}, berthShift: 15, terminalStatus: 'planned' });
  ok(r.line.includes('터미널 배정 15모브') && !r.line.includes('7.5'), '⑧ 홀수 모브는 대수로 바꾸지 않는다');
  r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: 'planned', keepConfN: 2 });
  ok(!r.line.includes('앞 기항지') && !r.whyUnknown, '⑪ 본선 잔류 확정 컨이 보이는 배는 «못 찾았다»고 말하지 않는다(감사 4.60)');
  r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: 'planned', keepN: 3 });
  ok(!r.whyUnknown, '⑫ 본선 잔류 예보(◆) 컨만 있어도 말하지 않는다');
  r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: '' });
  ok(!r.whyUnknown && !r.line.includes('앞 기항지'), '⑬ 터미널 상태가 빈 옛 항차는 말하지 않는다');
  r = core({ shiftingMap: {}, berthShift: 16, terminalStatus: 'planned' });
  ok(r.whyUnknown === true, '⑭ 켜졌을 때 whyUnknown 이 참(맨 윗줄이 같은 판정을 쓴다)');
  console.log(fail ? '실패 ' + fail : '통과');
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
